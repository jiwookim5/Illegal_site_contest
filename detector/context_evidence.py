def assess(normalized, enabled):
    """사용자가 꺼 둔 CAUTION 단어는 문맥 근거도 활성화하지 않는다."""
    hits = []
    for family, pattern in FAMILIES:
        matches = [m.group() for m in pattern.finditer(normalized)]
        eligible = [m for m in matches if any(word in m for word in enabled)]
        if eligible:
            hits.append({"family": family, "match": eligible[0]})
    return hits


def discount(evidence):
    return min(0.8, 0.5 * len(evidence))
